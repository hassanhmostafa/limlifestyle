export const researchReportBinding = z.object({
  archiveId: z.string().uuid(),
  reportRevision: z.number().int().min(1),
  snapshotSha256: z.string().regex(/^[a-f0-9]{64}$/),
});
export const researchPdfInput = researchReportBinding.extend({
  pdfBase64: z.string().min(8).max(14_000_000),
});
export const researchSessionCode = z.string().regex(/^LIM-[A-Za-z0-9-]{1,28}$/);
export function decodeResearchPdf(base64: string) {
  const text = base64.replace(/[\r\n]/g, ""),
    bytes = Buffer.from(text, "base64");
  if (
    bytes.toString("base64") !== text ||
    bytes.length > 10 * 1024 * 1024 ||
    !bytes.subarray(0, 5).equals(Buffer.from("%PDF-"))
  )
    throw new TRPCError({
      code: "BAD_REQUEST",
      message: "ملف التقرير غير صالح",
    });
  return bytes;
}

export async function approvedResearchContext(
  sessionId: number,
  expected?: z.infer<typeof researchReportBinding>
) {
  const care = await readCare(sessionId);
  if (!care.approvedAt)
    throw new TRPCError({
      code: "FORBIDDEN",
      message: "التقرير بانتظار الاعتماد",
    });
  const archive = await eventReportArchiveForSession(sessionId, care.revision);
  if (
    !archive ||
    (expected &&
      (archive.archiveId !== expected.archiveId ||
        archive.reportRevision !== expected.reportRevision ||
        archive.snapshotSha256 !== expected.snapshotSha256))
  )
    throw new TRPCError({
      code: "CONFLICT",
      message: "تغير التقرير المعتمد؛ حدّث الصفحة",
    });
  // The embedded encrypted approval is durable in LIM's existing DB. Never
  // fetch an S3 object or reconstruct missing measurements from live tables.
  const snapshot = readEmbeddedArchivedReportSnapshot(archive);
  if (
    !snapshot?.metadata ||
    snapshot.reportRevision !== archive.reportRevision ||
    snapshot.eventCode !== archive.eventCode
  )
    throw new TRPCError({
      code: "PRECONDITION_FAILED",
      message: "نسخة التقرير المعتمدة الثابتة غير متاحة",
    });
  return { archive, snapshot };
}

export async function researchSessionId(code: string) {
  const db = await getDb();
  if (!db) throw new TRPCError({ code: "SERVICE_UNAVAILABLE" });
  const [session] = await db
    .select({ id: eventParticipantSessions.id })
    .from(eventParticipantSessions)
    .where(
      and(
        eq(eventParticipantSessions.code, code),
        eq(eventParticipantSessions.eventCode, "lim-events")
      )
    )
    .limit(1);
  if (!session)
    throw new TRPCError({ code: "NOT_FOUND", message: "الجلسة غير موجودة" });
  return session.id;
}

export function preparedResearchMetadata(
  context: Awaited<ReturnType<typeof approvedResearchContext>>,
  pdf: Buffer,
  reissued: boolean
): ResearchPdfDeliveryMetadata {
  const { archive, snapshot } = context,
    hash = createHash("sha256").update(pdf).digest("hex");
  if (
    !reissued &&
    (!archive.originEligible ||
      archive.pdfSha256 !== hash ||
      Number(archive.pdfBytes) !== pdf.length)
  )
    throw new TRPCError({
      code: "CONFLICT",
      message: "الملف لا يطابق الأصل المسجل؛ يلزم إعادة إصدار موثقة من الأدمن",
    });
  return {
    contractVersion: 1,
    sourceSystem: "lim-lifestyle",
    // One reissue per immutable approval. Different regenerated bytes conflict
    // instead of silently creating another participant assessment.
    archiveId: reissued ? `${archive.archiveId}.reissued` : archive.archiveId,
    revision: archive.reportRevision,
    eventCode: archive.eventCode,
    templateVersion: snapshot.metadata!.templateVersion,
    size: pdf.length,
    pdfSha256: hash,
    ...(reissued
      ? {
          artifactKind: "reissued" as const,
          originalArchiveId: archive.archiveId,
          ...(archive.pdfSha256
            ? { originalPdfSha256: archive.pdfSha256 }
            : {}),
          approvedSnapshotSha256: archive.snapshotSha256,
        }
      : {}),
  };
}

export async function sendPreparedResearchReport(
  context: Awaited<ReturnType<typeof approvedResearchContext>>,
  base64: string,
  reissued = false
) {
  const pdf = decodeResearchPdf(base64),
    meta = preparedResearchMetadata(context, pdf, reissued);
  try {
    const receipt = await deliverResearchPdfBytes(meta, pdf);
    if (receipt.delivered) {
      await deliverAssessmentCompanion(
        buildAssessmentCompanion(context.snapshot, {
          archiveId: meta.archiveId,
          revision: meta.revision,
          reportPdfSha256: meta.pdfSha256,
          snapshotSha256: context.archive.snapshotSha256,
        }),
        context.snapshot.eventCode
      );
    }
    return receipt;
  } catch {
    throw new TRPCError({
      code: "SERVICE_UNAVAILABLE",
      message: "لم يتأكد استلام نسخة التقرير؛ احتفظ بالملف وأعد المزامنة",
    });
  }
}

export function publicResearchReissueContext(
  context: Awaited<ReturnType<typeof approvedResearchContext>>
) {
  const { archive, snapshot } = context;
  return {
    snapshot,
    binding: {
      archiveId: archive.archiveId,
      reportRevision: archive.reportRevision,
      snapshotSha256: archive.snapshotSha256,
    },
    filename: eventReportFilename(snapshot.metadata!, true),
  };
}
